// Generate src/design/tokens.css from src/design/tokens.json, the token file
// of the "voc-design system" (claude.ai artifact 4BT9dXPJCgTuAPYFe4VZus).
// To pick up a new version of the design system, replace tokens.json with its
// project/tokens.json and run `npm run tokens`. Never edit tokens.css by hand.
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../src/design/tokens.json", import.meta.url);
const target = new URL("../src/design/tokens.css", import.meta.url);
const tokens = JSON.parse(readFileSync(source, "utf8"));

// Fontsource registers the self-hosted faces as "Geist Variable" and
// "Geist Mono Variable"; name them first, then the design system's stack.
const selfHosted = { sans: '"Geist Variable"', mono: '"Geist Mono Variable"' };

// "{accent}" is an alias: it follows the referenced token in every theme.
const alias = (value) =>
  typeof value === "string"
    ? value.replace(/^\{([a-z0-9-]+)\}$/, "var(--$1)")
    : value;

const themes = tokens.color.themes.map((theme) => theme.id);
const [primary, ...others] = themes;
const themed = [...tokens.color.tokens, ...tokens.shadow.tokens];
const valueIn = (token, theme) =>
  alias(typeof token.value === "object" ? token.value[theme] : token.value);

const lines = [
  "/* Generated by scripts/tokens.mjs from tokens.json. Do not edit. */",
  "",
  `/* ${primary} is the default theme; others apply through data-theme. */`,
  ":root {",
  ...themed.map((token) => `  --${token.name}: ${valueIn(token, primary)};`),
  ...Object.entries(tokens.type.families).map(
    ([name, stack]) => `  --font-${name}: ${selfHosted[name]}, ${stack};`,
  ),
  ...[tokens.spacing, tokens.radius].flatMap((family) =>
    family.tokens.map((token) => `  --${token.name}: ${token.value};`),
  ),
  "}",
];
for (const theme of others) {
  lines.push(
    "",
    `:root[data-theme="${theme}"] {`,
    ...themed
      .filter((token) => typeof token.value === "object")
      .map((token) => `  --${token.name}: ${valueIn(token, theme)};`),
    "}",
  );
}
writeFileSync(target, `${lines.join("\n")}\n`);
console.log(`wrote ${target.pathname}`);
