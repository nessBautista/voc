def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def save(path, value):
    path = Path(path)
    tmp = path.with_suffix('.tmp')
    tmp.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n')
    tmp.replace(path)


def restore_topics(rows):
    return tuple(TopicRecord(**(r | {'keywords':tuple(Keyword(**k) for k in r['keywords']),
                                    'evidence_ids':tuple(r['evidence_ids'])})) for r in rows)


def prepare(repo, configs, representation):
    repo = Path(repo)
    original = repo/'data/experiments/julaug-2026'
    protocol = json.loads((original/'protocol.json').read_text())
    input_sets = {s:artifacts.read_input(protocol[k]) for s,k in [('base','sample'),('alternative','alternative_input')]}
    reference_path = repo/'data/experiments/julaug-2026-paso-a-paso/interpretation-run.json'
    reference = json.loads(reference_path.read_text())
    assert reference['state'] == 'completed'
    saved = {s:read_analysis(aid) for s,aid in reference['final_analyses'].items()}
    assert set(saved) == set(input_sets) == {'base','alternative'}
    sentiments = {}
    for s,inp in input_sets.items():
        historical = saved[s].reviews.set_index('record_id').loc[inp.reviews.record_id]
        assert historical.model_text.tolist() == inp.reviews.model_text.tolist()
        sentiments[s] = pd.DataFrame([asdict(x) for x in saved[s].sentiments]).set_index('record_id').loc[inp.reviews.record_id].reset_index()
        assert sentiments[s].status.eq('classified').all()
    base = input_sets['base'].reviews.set_index('record_id')
    alt = input_sets['alternative'].reviews.set_index('record_id')
    assert len(base)==1000 and len(alt)==987 and set(alt.index)<set(base.index)
    assert base.loc[alt.index,'model_text'].equals(alt.model_text)
    removed = base.loc[~base.index.isin(alt.index)].reset_index()
    assert len(removed)==13
    decisions = pd.read_csv(original/'relevance.csv')
    # The exact frozen subset was generated by the already trained filter.
    assert sha(original/'relevance.csv') == protocol['relevance_decisions_sha256']
    source_files = [original/'protocol.json', original/'relevance.csv',reference_path]
    source_files += [repo/f'data/analyses/{a.manifest.analysis_id}/manifest.json' for a in saved.values()]
    identity = {'schema':'voc-paired-sensitivity-v1',
                'inputs':{s:x.info['input_id'] for s,x in input_sets.items()},
                'configs':{k:v.as_dict() for k,v in configs.items()},'representation':asdict(representation),
                'saved_analyses':{s:a.manifest.analysis_id for s,a in saved.items()},
                'sources':{str(p.relative_to(repo)):sha(p) for p in source_files},
                'software':{p:version(p) for p in ['bertopic','umap-learn','hdbscan','numpy','scikit-learn','torch','sentence-transformers']},
                'code':{p:sha(repo/p) for p in ['src/voc_ml/topics/bertopic.py','src/voc_ml/topics/reduction.py','src/voc_ml/topics/representation.py']},
                'helper_sha256':sha(__file__)}
    study_id = fingerprint(identity)
    work = repo/'data/experiments/bertopic-sensibilidad-pareada'/study_id
    return SimpleNamespace(repo=repo,inputs=input_sets,saved=saved,sentiments=sentiments,removed=removed,
                           decisions=decisions,identity=identity,study_id=study_id,work=work,configs=configs,
                           representation=representation)


def grouping(ctx, *, allow_fit=False):
    results = {};new_fits=0
    for index,(name,configuration) in enumerate(ctx.configs.items(),1):
        for system,inp in ctx.inputs.items():
            print(f'[{index}/10] {name} · {system}: agrupamiento y representación',flush=True)
            sel=inp.info['selection']
            cfg=replace(configuration,selection=SelectionConfig(kind=sel['kind'],size=sel['size'],seed=sel['seed']))
            folder=ctx.work/'runs'/name/system
            if not (folder/'manifest.json').is_file():
                if name!='B0' and not allow_fit:
                    raise RuntimeError(f'Falta {name}/{system}. Habilita los ajustes locales para generarlo.')
                if folder.exists():
                    raise RuntimeError(f'Corrida incompleta: {name}/{system}. Inspeccionar antes de repetir.')
                folder.mkdir(parents=True)
                save(folder/'state.json',{'state':'running'})
                start=time.perf_counter()
                try:
                    if name=='B0':
                        parent=ctx.saved[system]
                        assignments=parent.assignments;topics=parent.topics
                        reused=True;reduction_reused=None
                    else:
                        reduction=reduce_inputs(inp,cfg.reduction,cache_dir=ctx.work/'reductions')
                        discovered=discover(inp,cfg,reduction=reduction)
                        view=SimpleNamespace(reviews=inp.reviews,assignments=discovered.assignments,
                                             topics=discovered.topics,manifest=SimpleNamespace(inputs=inp.info))
                        topics,_=refine(view,ctx.representation,local_files_only=True)
                        assignments=discovered.assignments
                        reused=False;reduction_reused=reduction.reused;new_fits+=1
                    save(folder/'records.json',{'assignments':[asdict(x) for x in assignments],
                                               'topics':[asdict(x) for x in topics]})
                    receipt={'state':'completed','study_id':ctx.study_id,'configuration':cfg.as_dict(),
                             'reused_published_B0':reused,'reduction_reused':reduction_reused,
                             'seconds':time.perf_counter()-start,'records_sha256':sha(folder/'records.json')}
                    save(folder/'manifest.json',receipt)
                    save(folder/'state.json',{'state':'completed'})
                except Exception as error:
                    save(folder/'state.json',{'state':'failed','error_type':type(error).__name__})
                    raise
            receipt=json.loads((folder/'manifest.json').read_text())
            assert receipt['study_id']==ctx.study_id and receipt['configuration']==cfg.as_dict()
            assert sha(folder/'records.json')==receipt['records_sha256']
            records=json.loads((folder/'records.json').read_text())
            assignments=tuple(ReviewAssignment(**x) for x in records['assignments'])
            topics=restore_topics(records['topics'])
            assert [x.record_id for x in assignments]==inp.reviews.record_id.tolist()
            view=SimpleNamespace(reviews=inp.reviews,assignments=assignments,topics=topics,
                                 manifest=SimpleNamespace(inputs=inp.info))
            frame=inp.reviews.merge(pd.DataFrame(records['assignments']),on='record_id',validate='one_to_one')
            frame=frame.merge(ctx.sentiments[system][['record_id','model_label']],on='record_id',validate='one_to_one')
            sizes=frame.topic_id.value_counts()
            table=pd.DataFrame([{'topic_id':t.topic_id,'size':int(sizes[t.topic_id]),
                                'keywords':' | '.join(k.term for k in t.keywords),
                                **{label:int(((frame.topic_id==t.topic_id)&(frame.model_label==label)).sum())
                                   for label in ['negative','neutral','positive']}} for t in topics])
            assert table[['negative','neutral','positive']].sum(axis=1).equals(table['size'])
            assert table['size'].sum()==len(inp.reviews)
            results[name,system]={'view':view,'frame':frame,'topics':table,'receipt':receipt}
            print(f'  {len(table.loc[table.topic_id.ge(0)])} tópicos · {int((frame.topic_id==-1).sum())} sin asignar',flush=True)
    return results,new_fits


def measurements(ctx, results):
    summaries=[];effects=[];transitions=[]
    common=ctx.inputs['alternative'].reviews.record_id.tolist()
    for name in ctx.configs:
        for system in ctx.inputs:
            frame=results[name,system]['frame'];assigned=frame.loc[frame.topic_id.ge(0),'topic_id'].value_counts()
            summaries.append({'configuration':name,'system':system,'rows':len(frame),'topics':len(assigned),
                              'unassigned':int(frame.topic_id.eq(-1).sum()),
                              'unassigned_pct':100*frame.topic_id.eq(-1).mean(),
                              'largest':int(assigned.max()) if len(assigned) else 0,
                              'largest_pct':100*assigned.max()/len(frame) if len(assigned) else 0})
        b=results[name,'base']['frame'].set_index('record_id');a=results[name,'alternative']['frame'].set_index('record_id')
        x=b.loc[common,'topic_id'].to_numpy();y=a.loc[common,'topic_id'].to_numpy()
        both=(x>=0)&(y>=0)
        effects.append({'configuration':name,'common_rows':len(common),'ari_common':adjusted_rand_score(x,y),
                        'assigned_intersection':int(both.sum()),
                        'ari_assigned_intersection':adjusted_rand_score(x[both],y[both]) if both.sum()>1 else None,
                        'became_unassigned':int(((x>=0)&(y==-1)).sum()),
                        'became_assigned':int(((x==-1)&(y>=0)).sum()),
                        'topics_if_only_deleting_rows':int(b.loc[common,'topic_id'].loc[lambda s:s>=0].nunique()),
                        'largest_if_only_deleting_rows':int(b.loc[common,'topic_id'].loc[lambda s:s>=0].value_counts().max())})
        c=pd.crosstab(pd.Series(x,name='base_topic'),pd.Series(y,name='alternative_topic'))
        for bt in c.index:
            for at in c.columns:
                if c.loc[bt,at]:transitions.append({'configuration':name,'base_topic':int(bt),'alternative_topic':int(at),'rows':int(c.loc[bt,at])})
    return pd.DataFrame(summaries),pd.DataFrame(effects),pd.DataFrame(transitions)


def build_requests(ctx,results):
    cfg=load_config(ctx.repo/'config/analysis/interpretation.toml')
    requests={};mapping=[]
    for (name,system),result in results.items():
        ids=sorted(t.topic_id for t in result['view'].topics if t.topic_id>=0)
        for start in range(0,len(ids),cfg.max_topics):
            for req in make_requests(result['view'],ids[start:start+cfg.max_topics],cfg):
                key=req['request_fingerprint']
                if key in requests:assert requests[key]==req
                requests[key]=req
                mapping.append({'configuration':name,'system':system,'topic_id':req['topic_id'],'request_fingerprint':key})
    return cfg,requests,pd.DataFrame(mapping)


def _cached(folder, key):
    path=folder/key
    if not (path/'record.json').exists():return None
    record=json.loads((path/'record.json').read_text())
    for name,h in record['files'].items():assert sha(path/name)==h
    assert fingerprint(json.loads((path/'request.json').read_text()))==key
    response=json.loads((path/'response.json').read_text())
    if record['status']=='completed':assert normalize(response,record['evidence_ids'])==record['result']
    return record


def plan_llm(ctx,requests):
    cache=ctx.work/'llm';cache.mkdir(parents=True,exist_ok=True)
    records={};missing={}
    for key,req in requests.items():
        old=_cached(cache,key)
        if old is not None:records[key]=old
        elif (cache/key).exists():raise RuntimeError('Una solicitud quedó incompleta. Inspeccionar su estado antes de continuar.')
        else:missing[key]=req
    reusable=find_reusable(list(missing.values())) if missing else {}
    for key,match in reusable.items():
        req=missing.pop(key);folder=cache/key;folder.mkdir()
        (folder/'request.json').write_bytes(match['request_bytes'])
        (folder/'response.json').write_bytes(match['response_bytes'])
        result=normalize(json.loads(match['response_bytes']),req['evidence_ids'])
        record={'status':'completed','origin':'published_reuse','result':result,'evidence_ids':req['evidence_ids'],
                'error':None,'cost_usd':0,'charged_or_reserved_usd':0,'provider_attempt':False,
                'analysis_id':match['analysis_id'],
                'files':{p.name:sha(p) for p in folder.iterdir() if p.is_file()}}
        save(folder/'record.json',record);records[key]=record
    plan={'unique_requests':len(requests),'published_reused':sum(r['origin']=='published_reuse' for r in records.values()),
          'cached_provider_attempts':sum(r['provider_attempt'] for r in records.values()),
          'pending_requests':len(missing),'failures_retained':sum(r['status']!='completed' for r in records.values())}
    save(ctx.work/'llm-plan.json',plan)
    return records,missing,plan


def _catalog(ctx):
    url='https://openrouter.ai/api/v1/models/google/gemini-2.5-flash/endpoints'
    with urllib.request.urlopen(url,timeout=30) as response:catalog=json.load(response)
    active=[e for e in catalog['data']['endpoints'] if e['status']==0]
    assert active
    # Upper price among active endpoints, with no free/discount assumptions.
    prompt=max(Decimal(e['pricing']['prompt']) for e in active)
    completion=max(Decimal(e['pricing']['completion']) for e in active)
    record={'observed_at':datetime.now(timezone.utc).isoformat(),'url':url,'prompt_usd_per_token':str(prompt),
            'completion_usd_per_token':str(completion),'catalog':catalog}
    save(ctx.work/'llm-catalog.json',record)
    return prompt,completion


def interpret_all(ctx,requests, *, live=False,max_usd=2.0,max_attempts=500,workers=4):
    records,missing,plan=plan_llm(ctx,requests)
    print('Plan LLM:',plan,flush=True)
    if not missing:return records,{'new_provider_attempts':0,'new_cost_usd':0,'budget_usd':max_usd}
    if not live:
        raise RuntimeError('Hay interpretaciones pendientes. Habilita EJECUTAR_LLM para solicitar únicamente las faltantes.')
    if not os.environ.get('OPENROUTER_API_KEY','').strip():raise RuntimeError('Falta la credencial inyectada OPENROUTER_API_KEY.')
    input_price,output_price=_catalog(ctx)
    budget=Decimal(str(max_usd))
    accounted=sum(Decimal(str(r['charged_or_reserved_usd'])) for r in records.values())
    previous=sum(r['provider_attempt'] for r in records.values())
    queue=list(missing.items());started=0;actual_new=Decimal('0')
    cache=ctx.work/'llm'
    def reserve(key,req):
        # Conservative byte-count planning, not a provider-side hard monetary cap.
        content=json.dumps(req['request']['body'],ensure_ascii=False).encode('utf-8')
        allowance=(Decimal(len(content)+4096)*input_price+Decimal(req['request']['body']['max_tokens'])*output_price)*Decimal('1.2')
        folder=cache/key;folder.mkdir(exist_ok=False)
        save(folder/'request.json',req['request'])
        save(folder/'reservation.json',{'allowance_usd':str(allowance),'state':'reserved','at':datetime.now(timezone.utc).isoformat()})
        return allowance
    def execute(key,req,allowance):
        folder=cache/key
        client=openrouter.create_client()
        try:response=openrouter.request(client,req['request']['body'])
        finally:client.close()
        save(folder/'response.json',response)
        error=None;result=None
        try:result=normalize(response,req['evidence_ids'])
        except (ValueError,TypeError,KeyError,IndexError):error='provider_error' if response.get('error') else 'invalid_response'
        usage=response.get('usage') or {}
        cost=usage.get('cost');cost=Decimal(str(cost)) if cost is not None else None
        if cost is not None and (not cost.is_finite() or cost<0):cost=None
        charge=cost if cost is not None else allowance
        record={'status':'completed' if error is None else 'failed','origin':'provider','result':result,
                'evidence_ids':req['evidence_ids'],'error':error,'provider_attempt':True,
                'cost_usd':float(cost) if cost is not None else None,'charged_or_reserved_usd':float(charge),
                'usage':usage,'model':response.get('model'),'response_id':response.get('id'),
                'files':{p.name:sha(p) for p in [folder/'request.json',folder/'response.json',folder/'reservation.json']}}
        save(folder/'record.json',record)
        return key,record
    # Each batch reserves its entire planning allowance before dispatching.
    with ThreadPoolExecutor(max_workers=workers) as pool:
        while queue:
            batch=[];reserved=Decimal('0')
            while queue and len(batch)<workers:
                key,req=queue[0]
                amount=(Decimal(len(json.dumps(req['request']['body'],ensure_ascii=False).encode('utf-8'))+4096)*input_price+Decimal(req['request']['body']['max_tokens'])*output_price)*Decimal('1.2')
                if accounted+reserved+amount>budget or previous+started+len(batch)>=max_attempts:break
                queue.pop(0);allowance=reserve(key,req);reserved+=allowance
                batch.append((key,req,allowance))
            if not batch:raise RuntimeError('Presupuesto o máximo de intentos alcanzado. Los resultados parciales están guardados.')
            started+=len(batch)
            futures=[pool.submit(execute,*job) for job in batch]
            for future in as_completed(futures):
                key,record=future.result();records[key]=record
                accounted+=Decimal(str(record['charged_or_reserved_usd']))
                if record['cost_usd'] is not None:actual_new+=Decimal(str(record['cost_usd']))
                print(f'LLM {len(records)}/{len(requests)} · {record["status"]} · contabilizado USD {accounted:.4f}',flush=True)
                save(ctx.work/'llm-progress.json',{'completed_requests':len(records),'total_requests':len(requests),
                     'new_provider_attempts':started,'accounted_usd':str(accounted),'new_known_cost_usd':str(actual_new),
                     'failed':sum(r['status']!='completed' for r in records.values())})
    assert set(records)==set(requests)
    return records,{'new_provider_attempts':started,'new_cost_usd':float(actual_new),'accounted_usd':float(accounted),'budget_usd':max_usd,
                    'failed':sum(r['status']!='completed' for r in records.values()),'automatic_retries':0}


def catalog(results,mapping,records):
    tables=[]
    for (name,system),data in results.items():
        rows=data['topics'].copy();rows['configuration']=name;rows['system']=system
        rows=rows.merge(mapping,on=['configuration','system','topic_id'],how='left',validate='one_to_one')
        for i,row in rows.iterrows():
            if row.topic_id==-1:
                values={'llm_status':'not_applicable','llm_name':'Sin tópico (−1)','assessment':'not_applicable','description':'',
                        'proposed_feature':'','interpretation_origin':'not_applicable','llm_error':''}
            else:
                rec=records[row.request_fingerprint];result=rec['result'] or {}
                values={'llm_status':rec['status'],'llm_name':result.get('name','Respuesta fallida'),
                        'assessment':result.get('assessment','failed'),'description':result.get('topic_description',''),
                        'proposed_feature':result.get('proposed_feature') or '',
                        'interpretation_origin':rec['origin'],'llm_error':rec['error'] or ''}
            for col,value in values.items():rows.loc[i,col]=value
        tables.append(rows)
    return pd.concat(tables,ignore_index=True)
